#!/usr/bin/env python3
"""Rebuild _bibliography/papers.bib from the ORCID record.

The work list comes from the ORCID public API; BibTeX metadata comes from Crossref.
Only journal articles with a DOI are included. If any DOI cannot be resolved, the
script exits without writing so a partial list is never committed.
"""

import json
import re
import sys
import unicodedata
import urllib.parse
import urllib.request
from pathlib import Path

ORCID_ID = "0000-0002-9962-3691"
ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "_bibliography" / "papers.bib"
USER_AGENT = "qusichao-website/1.0 (mailto:qsc4977@gmail.com)"


def fetch_json(url):
    request = urllib.request.Request(
        url, headers={"Accept": "application/json", "User-Agent": USER_AGENT}
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.load(response)


def journal_article_dois():
    data = fetch_json(f"https://pub.orcid.org/v3.0/{ORCID_ID}/works")
    dois = set()
    for group in data.get("group", []):
        summary = group["work-summary"][0]
        if summary.get("type") != "journal-article":
            continue
        for ext in (group.get("external-ids") or {}).get("external-id", []):
            if ext.get("external-id-type") == "doi":
                dois.add(ext["external-id-value"].lower())
                break
    return sorted(dois)


def strip_markup(text):
    return re.sub(r"<[^>]+>", "", text).strip()


def bib_escape(text):
    return re.sub(r"([&%$#_])", r"\\\1", text)


def ascii_slug(text):
    normalized = unicodedata.normalize("NFKD", text)
    return re.sub(r"[^a-z0-9]", "", normalized.encode("ascii", "ignore").decode().lower())


def year_of(message):
    for key in ("published-print", "published-online", "published", "issued"):
        parts = (message.get(key) or {}).get("date-parts", [[None]])[0]
        if parts and parts[0]:
            return str(parts[0])
    return "n.d."


def author_field(authors):
    names = []
    for author in authors:
        if "family" in author:
            given = author.get("given", "")
            names.append(f"{author['family']}, {given}".rstrip(", "))
        elif "name" in author:
            names.append("{" + author["name"] + "}")
    return " and ".join(names)


def build_entry(message, used_keys):
    authors = message.get("author", [])
    year = year_of(message)
    title = strip_markup((message.get("title") or [message["DOI"]])[0])
    journal = (message.get("container-title") or message.get("short-container-title") or [""])[0]

    first_family = authors[0].get("family", authors[0].get("name", "paper")) if authors else "paper"
    first_word = ascii_slug(title.split()[0]) if title.split() else "paper"
    base_key = f"{ascii_slug(first_family) or 'paper'}{year}{first_word}"
    key, suffix = base_key, 2
    while key in used_keys:
        key = f"{base_key}{suffix}"
        suffix += 1
    used_keys.add(key)

    fields = [
        ("title", "{" + bib_escape(title) + "}"),
        ("author", author_field(authors)),
        ("journal", bib_escape(journal)),
        ("year", year),
        ("volume", message.get("volume", "")),
        ("number", message.get("issue", "")),
        ("pages", (message.get("page") or "").replace("-", "--")),
        ("doi", message["DOI"]),
    ]
    body = ",\n".join(f"  {name}={{{value}}}" for name, value in fields if value)
    return year, title, f"@article{{{key},\n{body}\n}}\n"


def main():
    dois = journal_article_dois()
    if not dois:
        print("No journal articles with DOIs found on ORCID; nothing written.", file=sys.stderr)
        return 1

    entries, failed, used_keys = [], [], set()
    for doi in dois:
        try:
            url = "https://api.crossref.org/works/" + urllib.parse.quote(doi, safe="/")
            message = fetch_json(url)["message"]
        except Exception as error:
            failed.append((doi, str(error)))
            continue
        entries.append(build_entry(message, used_keys))

    if failed:
        for doi, error in failed:
            print(f"Failed to resolve {doi}: {error}", file=sys.stderr)
        print("Aborted without writing papers.bib.", file=sys.stderr)
        return 1

    entries.sort(key=lambda item: (item[0], item[1]), reverse=True)
    header = (
        "% Auto-generated by bin/update_publications.py from ORCID "
        f"{ORCID_ID} and Crossref. Do not edit by hand.\n\n"
    )
    OUTPUT.write_text(header + "\n".join(text for _, _, text in entries), encoding="utf-8")
    print(f"Wrote {len(entries)} entries to {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
